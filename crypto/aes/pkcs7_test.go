func Test_applyPKCS7Padding(t *testing.T) {
	type arg struct {
		givenBytes []byte
		expResult  []byte
	}
	tcs := map[string]arg{
		"ok: lt 16": {
			givenBytes: []byte("abc"),
			expResult:  []byte{0x61, 0x62, 0x63, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd},
		},
		"ok: gt 16": {
			givenBytes: []byte("abcdefghijklmnopqrstuvwxyz"),
			expResult:  []byte{0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0x6, 0x6, 0x6, 0x6, 0x6, 0x6},
		},
	}
	for scenario, tc := range tcs {
		t.Run(scenario, func(t *testing.T) {
			t.Parallel()
			// Given

			// When
			result := applyPKCS7Padding(tc.givenBytes)

			// Then
			require.Equal(t, tc.expResult, result)
		})
	}
}

func Test_stripPKCS7Padding(t *testing.T) {
	type arg struct {
		givenBytes []byte
		expResult  []byte
		expErr     error
	}
	tcs := map[string]arg{
		"err: input not enough length": {
			givenBytes: []byte{0x61, 0x62, 0x63, 0xd, 0xd, 0xd},
			expErr:     ErrInvalidData,
		},
		"err: length eq 0": {
			givenBytes: []byte{},
			expErr:     ErrInvalidData,
		},
		"err: invalid padding length": {
			givenBytes: []byte{0x61, 0x62, 0x63, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd},
			expErr:     ErrInvalidPaddingValue,
		},
		//"ok: lt 16": {
		//	givenBytes: []byte{0x61, 0x62, 0x63, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd},
		//	expResult:  []byte{0x61, 0x62, 0x63, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd, 0xd},
		//},
		//"ok: gt 16": {
		//	givenBytes: []byte("abcdefghijklmnopqrstuvwxyz"),
		//	expResult:  []byte{0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68, 0x69, 0x6a, 0x6b, 0x6c, 0x6d, 0x6e, 0x6f, 0x70, 0x71, 0x72, 0x73, 0x74, 0x75, 0x76, 0x77, 0x78, 0x79, 0x7a, 0x6, 0x6, 0x6, 0x6, 0x6, 0x6},
		//},
	}
	for scenario, tc := range tcs {
		t.Run(scenario, func(t *testing.T) {
			t.Parallel()
			// Given

			// When
			result, err := stripPKCS7Padding(tc.givenBytes)

			// Then
			if tc.expErr != nil {
				require.EqualError(t, err, tc.expErr.Error())
			} else {
				require.NoError(t, err)
				require.Equal(t, tc.expResult, result)
			}
		})
	}
}
